#!/usr/bin/env node
/**
 * Create a portable `pi` CLI shim next to the bundled Node runtime so the
 * packaged app does not require a global `pi` install.
 *
 * Writes:
 *   .next/standalone/bin/pi      (unix shell wrapper)
 *   .next/standalone/bin/pi.cmd  (windows)
 *
 * Points at the already-vendored @earendil-works/pi-coding-agent package.
 */
import { chmodSync, existsSync, mkdirSync, writeFileSync } from "fs";
import { join } from "path";

const root = process.cwd();
const standalone = join(root, ".next", "standalone");
const binDir = join(standalone, "bin");
const isWin = process.platform === "win32";

const cliJs = join(
  standalone,
  "node_modules",
  "@earendil-works",
  "pi-coding-agent",
  "dist",
  "cli.js",
);
const nodeBin = join(binDir, isWin ? "node.exe" : "node");

// Same as bundle-runtime-node.mjs: the Next entry is pruned for desktop builds.
if (!existsSync(join(standalone, "daemon", "ipc-host.mjs")) && !existsSync(join(standalone, "server.js"))) {
  console.error("Missing prepared standalone tree — run scripts/prepare-electron-standalone.mjs first.");
  process.exit(1);
}
if (!existsSync(cliJs)) {
  console.error(`Missing pi CLI entry: ${cliJs}`);
  process.exit(1);
}
if (!existsSync(nodeBin)) {
  console.error(`Missing bundled Node: ${nodeBin} — run bundle-runtime-node.mjs first.`);
  process.exit(1);
}

mkdirSync(binDir, { recursive: true });

// Unix shim: use the node binary sitting next to this script.
const unixShim = `#!/bin/sh
# Auto-generated by scripts/bundle-pi-cli.mjs — do not edit.
DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
NODE="$DIR/node"
CLI="$DIR/../node_modules/@earendil-works/pi-coding-agent/dist/cli.js"
if [ ! -x "$NODE" ]; then
  echo "pi: bundled Node missing at $NODE" >&2
  exit 127
fi
if [ ! -f "$CLI" ]; then
  echo "pi: CLI entry missing at $CLI" >&2
  exit 127
fi
exec "$NODE" "$CLI" "$@"
`;

const winShim = `@echo off
REM Auto-generated by scripts/bundle-pi-cli.mjs — do not edit.
set "DIR=%~dp0"
set "NODE=%DIR%node.exe"
set "CLI=%DIR%..\\node_modules\\@earendil-works\\pi-coding-agent\\dist\\cli.js"
if not exist "%NODE%" (
  echo pi: bundled Node missing at %NODE% 1>&2
  exit /b 127
)
if not exist "%CLI%" (
  echo pi: CLI entry missing at %CLI% 1>&2
  exit /b 127
)
"%NODE%" "%CLI%" %*
`;

const piPath = join(binDir, "pi");
const piCmdPath = join(binDir, "pi.cmd");
writeFileSync(piPath, unixShim, { encoding: "utf8", mode: 0o755 });
try { chmodSync(piPath, 0o755); } catch { /* ignore */ }
writeFileSync(piCmdPath, winShim, "utf8");

console.log(`Bundled pi CLI shim → ${piPath}`);
console.log(`Bundled pi.cmd     → ${piCmdPath}`);
